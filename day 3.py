"""
Numeric DT(integer,float,complex)
string DT
Boolean DT(True,False)
NoneType DT
sequence DT



"""

#numeric dt
age=67
print(age)
print(type(age))
print(age,type(age),sep="-")

#string DT
d="welcome"
print(d,type(d))


#boolean DT
prog=True
print(prog, type(prog))

#None
empty=None
print(empty,type(empty))

#sequence DT


std1= ["sai",34,3,"python"]
print(std1,type(std1))

std2= ("dungi",35,4,"python")
print(std2,type(std2))

std3={"limbu",36,5,"python"}
print(std3,type(std3))

std4= {"name":"lungi","age":9,"rollno":23,"course":"python"}
print(std4,type(std4 ))


